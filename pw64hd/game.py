"""Running Birdman64 headless (or briefly windowed) from a work folder.

Every run uses a scratch data folder (work/data) and a copy of the unlocked
scratch save, so the user's own saves and settings are never touched.
Textures are dumped by Birdman64 itself (PW64_DUMP_TEX=1) to work/tmp/tex.
"""
import glob
import os
import shutil
import subprocess
import time


class Game:
    def __init__(self, exe, rom, work):
        self.exe, self.rom, self.work = exe, rom, work
        self.data = os.path.join(work, "data")
        self.tex = os.path.join(work, "tmp", "tex")
        self.logs = os.path.join(work, "logs")
        self.unlocked = os.path.join(work, "unlocked.eep")
        for d in (self.data, self.tex, self.logs):
            os.makedirs(d, exist_ok=True)

    def env(self, **extra):
        e = dict(os.environ)
        for k in [k for k in e if k.startswith("PW64_")]:
            del e[k]  # never inherit the user's own overrides
        e.update(PW64_ROM=self.rom, PW64_DATA_DIR=self.data, PW64_NO_DIALOGS="1",
                 PW64_NO_AUDIO="1", PW64_NO_INPUT="1")
        e.update({k: str(v) for k, v in extra.items()})
        return e

    def run(self, name, env, timeout=None):
        """Run the game; output goes to a log file. (Never pipe its output into
        something that closes early: Birdman64 panics on a closed stderr.)"""
        log = os.path.join(self.logs, name + ".log")
        with open(log, "w", encoding="utf-8", errors="replace") as lf:
            p = subprocess.run([self.exe], cwd=self.work, env=env, stdout=lf,
                               stderr=subprocess.STDOUT, timeout=timeout)
        return p.returncode, log

    def tex_count(self):
        return len(glob.glob(os.path.join(self.tex, "*.png")))

    # -- one-time steps ---------------------------------------------------
    def first_build(self):
        """First start compiles the game module from the ROM (Birdman64 does
        this itself; it downloads the decompilation once)."""
        code, log = self.run("first_build", self.env(PW64_BUILD_ONLY="1"), timeout=3600)
        if code != 0:
            raise RuntimeError(f"Birdman64 could not build the game from your ROM - see {log}")

    def unlock(self):
        """All-gold scratch save via Birdman64's own 'Unlock everything' cheat,
        driven by its settings-screen automation. This shows a window for a few
        seconds (the settings screen needs a real window)."""
        if os.path.exists(self.unlocked):
            return
        eep = os.path.join(self.data, "pw64.eep")
        # a short headless run creates a blank save first
        self.run("make_save", self.env(PW64_MAX_RETRACES=200, PW64_NO_THROTTLE=1))
        keys = ",".join(["Down"] * 8 + ["Enter", "Enter"])  # row 9 = Unlock everything (v1.5.1)
        self.run("unlock", self.env(PW64_SETTINGS_SHOT=300, PW64_SETTINGS_KEYS=keys), timeout=300)
        # the cheat restarts the game once; wait for any restarted copy to exit
        for _ in range(60):
            if not _running("Birdman64.exe"):
                break
            time.sleep(2)
        if not os.path.exists(eep + ".before-unlock"):
            raise RuntimeError("Unlocking the scratch save failed - see work/logs/unlock.log")
        shutil.copy(eep, self.unlocked)

    # -- scripted, headless play -------------------------------------------
    def play(self, name, lines, retraces, dump_tex=True):
        gen = os.path.join(self.work, "scripts")
        os.makedirs(gen, exist_ok=True)
        script = os.path.join(gen, name + ".txt")
        with open(script, "w") as f:
            f.write("# generated by pw64hd\n" + "\n".join(lines) + "\n")
        eep = os.path.join(self.data, "run.eep")
        shutil.copy(self.unlocked, eep)  # fresh copy: the game may rewrite it
        env = self.env(PW64_EEP=eep, PW64_NO_THROTTLE=1, PW64_INFINITE_LOD=1,
                       PW64_INFINITE_VIEW_DISTANCE=1, PW64_WIDESCREEN="16:9",
                       PW64_TEX_PACKS=os.path.join(self.work, "no-pack"),
                       PW64_INPUT_SCRIPT=script, PW64_MAX_RETRACES=retraces)
        if dump_tex:
            env["PW64_DUMP_TEX"] = "1"
        before = self.tex_count()
        self.run(name, env, timeout=1800)
        return self.tex_count() - before


def _running(image):
    try:
        out = subprocess.run(["tasklist", "/FI", f"IMAGENAME eq {image}", "/NH"],
                             capture_output=True, text=True).stdout
        return image.lower() in out.lower()
    except OSError:
        return False
